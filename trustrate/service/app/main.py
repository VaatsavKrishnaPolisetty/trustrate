ROOT = Path(__file__).resolve().parents[2]
# This file is generated by PHP, is ignored, and contains only local service
# configuration. Do not read IBM credentials for ordinary review inference.
LOCAL = dotenv_values(ROOT / "db/.local/compose.env")

def setting(name, default=""):
    return os.environ.get(name, LOCAL.get(name, default))

ARTIFACTS = Path(setting("MODEL_ARTIFACT_DIR", str(ROOT / "service/artifacts")))
MODEL_PATH = Path(setting("MODEL_ARTIFACT", str(ARTIFACTS / "model.joblib")))
API_KEY = setting("SCORING_API_KEY")
model = None
inference_lock = Lock()
rate_lock = Lock()
requests_by_client = defaultdict(deque)

@asynccontextmanager
async def lifespan(app):
    global model
    if not API_KEY or len(API_KEY) < 24:
        raise RuntimeError("Configure a generated SCORING_API_KEY before starting the service")
    if MODEL_PATH.exists():
        model = TrustRateModel.load(MODEL_PATH)
    jobs.recover()
    yield

app = FastAPI(title="TrustRate real model service", version="2.0.0",
              lifespan=lifespan, docs_url=None, redoc_url=None, openapi_url=None)

def authenticate(request: Request, x_api_key: str = Header(default="")):
    if not API_KEY or not hmac.compare_digest(x_api_key, API_KEY):
        raise HTTPException(401, "Invalid API key")
    now = time.monotonic()
    client = request.client.host if request.client else "unknown"
    with rate_lock:
        recent = requests_by_client[client]
        while recent and recent[0] <= now - 60:
            recent.popleft()
        if len(recent) >= 240:
            raise HTTPException(429, "Scoring rate limit exceeded", headers={"Retry-After": "60"})
        recent.append(now)

def connect():
    try:
        return pymysql.connect(
            host=setting("DB_READONLY_HOST", setting("DB_HOST", "127.0.0.1")),
            port=int(setting("DB_PORT", "3306")), database=setting("DB_NAME", "trustrate"),
            user=setting("DB_READONLY_USER", "trustrate_reader"),
            password=setting("DB_READONLY_PASSWORD"), charset="utf8mb4",
            cursorclass=pymysql.cursors.DictCursor, connect_timeout=5,
            read_timeout=20, init_command="SET time_zone = '+00:00'",
        )
    except (pymysql.MySQLError, ValueError):
        raise HTTPException(503, "Read-only database unavailable") from None

def snapshot(ids):
    # A consistent full-history snapshot is essential: IP/account counts cross
    # products and text similarity includes the entire earlier product history.
    with connect() as conn:
        with conn.cursor() as cursor:
            cursor.execute("SELECT r.id,r.product_id,r.user_id,r.rating,r.body,r.ip_hash,"
                           "r.ip_prefix,r.user_agent,r.revision,r.created_at,r.status,"
                           "u.created_at AS account_created FROM reviews r "
                           "JOIN users u ON u.id=r.user_id "
                           "WHERE NOT (r.status='deleted' AND r.split='demo') "
                           "AND (r.source_id IS NULL OR r.source_id LIKE 'v3-%') "
                           "ORDER BY r.created_at,r.id")
            rows = cursor.fetchall()
    for row in rows:
        for field in ("created_at", "account_created"):
            row[field] = row[field].replace(tzinfo=timezone.utc).isoformat()
        row["ip_prefix"] = row["ip_prefix"] or "unknown"
        row["user_agent"] = row["user_agent"] or "unknown"
    lookup = {row["id"]: row for row in rows}
    if any(rid not in lookup or lookup[rid]["status"] == "deleted" for rid in ids):
        raise HTTPException(404, "Review not found or deleted")
    return [lookup[rid] for rid in ids], rows

def predict(ids,mode="aer",progress=lambda update:None):
    if model is None:
        raise HTTPException(503, "No trained model; run python -m pipeline.cli build")
    started = time.perf_counter()
    selected, history = snapshot(ids)
    with inference_lock:
        X = model.features.transform(selected, history=history)
        measured = model.scores(X)
        standardized = np.abs(model.scaler.transform(preprocess_features(X)))
    execution={"backend":model.backend,"ibm_job_id":None,"fallback_reason":None}
    if mode!="aer":
        from .quantum_execution import quantum_raw
        alternate,execution=quantum_raw(model,X,mode,progress)
        with inference_lock:
            raw=model.raw_scores(X)
        raw["quantum_ocsvm"]=alternate
        measured=model._normalize(raw)
        measured["hybrid_unguarded"]=measured["hybrid"].copy()
        if hasattr(model,"guard_upper"):
            measured["hybrid"]=guarded_score(measured["hybrid"],model.operational_guard(X))
    results = []
    for index, row in enumerate(selected):
        hybrid = float(measured["hybrid"][index])
        label = model.label_score(hybrid)
        reasons = []
        for j in np.argsort(-standardized[index])[:3]:
            feature = FEATURE_NAMES[j]
            code, description = REASON_DETAILS[feature]
            reasons.append({"code": code, "description": description, "feature": feature,
                            "value": float(X[index, j]),
                            "training_z_magnitude": float(standardized[index, j])})
        results.append({"review_id": row["id"], "review_revision": row["revision"],
                        "classical_score": float((measured["isolation_forest"][index] + measured["classical_ocsvm"][index]) / 2),
                        "quantum_score": float(measured["quantum_ocsvm"][index]),
                        "hybrid_score": hybrid, "label": label, "reasons": reasons,
                        "hybrid_unguarded":float(measured.get("hybrid_unguarded",measured["hybrid"])[index]),
                        "score_definition":"Two-signal operational guard plus model ranking; not a probability of fraud",
                        **execution,"model_version":model.model_version,
                        "calibration_backend":"aer_simulator",
                        "experimental":mode!="aer",
                        "latency_ms":round((time.perf_counter()-started)*1000)})
    return results

class ScoreRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")
    review_id: int = Field(gt=0, strict=True)
    mode: str = "aer"

class BatchRequest(BaseModel):
    model_config = ConfigDict(extra="forbid",strict=True)
    review_ids: list[int] = Field(min_length=1, max_length=128)
    mode: Literal["aer","aer_noise","ibm","ibm_with_fallback"] = "aer"
    asynchronous: bool = Field(default=False,alias="async")

@app.get("/health")
def health():
    try:
        with connect() as conn:
            with conn.cursor() as c:
                c.execute("SELECT 1")
        database = True
    except HTTPException:
        database = False
    return {"status": "ready" if model and database else "not_ready", "model_loaded": model is not None,
            "database_connected": database, "active_backend": model.backend if model else None}

@app.post("/v1/score", dependencies=[Depends(authenticate)])
def score(body: ScoreRequest):
    if body.mode != "aer":
        raise HTTPException(422, "Live scoring supports aer; use the explicit asynchronous hardware CLI for IBM experiments")
    return predict([body.review_id])[0]

@app.post("/v1/score/batch", dependencies=[Depends(authenticate)])
def batch(body: BatchRequest):
    if len(set(body.review_ids)) != len(body.review_ids) or any(r <= 0 for r in body.review_ids):
        raise HTTPException(422,"Use unique positive review IDs")
    if body.mode!="aer" or body.asynchronous:
        if not body.asynchronous or (body.mode!="aer" and len(body.review_ids)>4):
            raise HTTPException(422,"Hardware/noise experiments require async=true and at most 4 reviews")
        snapshot(body.review_ids)
        try:
            from fastapi.responses import JSONResponse
            return JSONResponse(status_code=202,content=jobs.submit(body.review_ids,body.mode,predict))
        except RuntimeError:
            raise HTTPException(409,"A batch is already active; poll its receipt, do not resubmit") from None
    return {"results": predict(body.review_ids)}

@app.get("/v1/jobs/{job_id}",dependencies=[Depends(authenticate)])
def job(job_id:str):
    try: return jobs.get(job_id)
    except KeyError: raise HTTPException(404,"Job not found") from None

@app.get("/v1/model", dependencies=[Depends(authenticate)])
def metadata():
    if model is None:
        raise HTTPException(503, "Model is not loaded")
    return model.metadata

@app.get("/v1/models", dependencies=[Depends(authenticate)])
def metrics():
    path = ARTIFACTS / "metrics.json"
    if not path.exists():
        raise HTTPException(503, "No evaluation artifact")
    return json.loads(path.read_text())
